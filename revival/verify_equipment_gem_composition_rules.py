"""Ordinary gem composition examples from the original client and policy."""
from dataclasses import replace
from inventory import ItemState
from equipment_gem_composition import CompositionRules,plan,decode


def refused(fn):
    try:fn()
    except ValueError:return
    raise AssertionError('Invalid composition was accepted')


def main():
    rules=CompositionRules.load()
    first=ItemState(901,7,35001,2,0,None,0)
    result=plan(rules,first,first,(0,0),0,9999)
    assert (result.success,result.output_template,result.output_binding,result.stamina_cost,result.success_percent)==(True,35014,0,35,100)
    assert result.debits==((901,2),)
    assert decode(0xc0424,bytes.fromhex('0000038500000385'))==(901,901)
    for payload in (b'',b'\0'*7,b'\0'*9,b'\0'*8,bytes.fromhex('ffffffff00000385')):
        refused(lambda:decode(0xc0424,payload))
    refused(lambda:decode(0xc0425,bytes.fromhex('0000038500000385')))
    # Literal original examples: level10 base55 + study3 bonus18 ->73%,
    # stamina80. The exact cutoff is the local designed RNG adoption.
    high=replace(first,template_id=35118,quantity=3)
    bound=replace(high,id=902,slot=1,binding=1)
    success=plan(rules,high,bound,(0,0),3,7299)
    failed=plan(rules,high,bound,(0,0),3,7300)
    assert (success.success_percent,success.stamina_cost,success.output_template,success.output_binding)==(73,80,35131,1)
    assert success.debits==((901,1),(902,1))
    assert failed.success is False and failed.output_template is None and failed.output_binding is None
    assert failed.debits==((902,1),) and failed.stamina_cost==80
    assert plan(rules,high,high,(0,0),0,9999).debits==((901,1),)
    assert plan(rules,high,bound,(0,0),6,9999).success
    for bad in (replace(first,quantity=1),replace(first,template_id=35183),replace(first,template_id=35214),
            replace(first,template_id=35221),replace(first,template_id=35425),replace(first,quality=0),
            replace(first,equipment_slot=0),replace(first,binding=2),replace(first,quantity=True)):
        refused(lambda:plan(rules,bad,bad,(0,0),0,0))
    refused(lambda:plan(rules,first,replace(first,id=902,template_id=35002),(0,0),0,0))
    refused(lambda:plan(rules,first,replace(first,id=902,role_id=8),(0,0),0,0))
    for flags in ((160,0),(32,0),(128,0),(2,0),(True,0),(1,0)):
        refused(lambda:plan(rules,first,first,flags,0,0))
    for level,draw in ((True,0),(7,0),(-1,0),(0,True),(0,-1),(0,10000)):
        refused(lambda:plan(rules,first,first,(0,0),level,draw))
    assert len(rules.gems)==210
    # Each original family advances to its own catalog row. These chains were
    # verified from original config.pfs in the source report, not generated by
    # the production result and then used as its expectation.
    for start,next_key in ((35000,35013),(35001,35014),(35002,35015),(35003,35016),
            (35004,35017),(35005,35018),(35006,35019),(35007,35020),(35008,35021),
            (35009,35022),(35010,35023),(35011,35024),(35012,35025),(35200,35201)):
        item=replace(first,template_id=start)
        assert plan(rules,item,item,(0,0),0,0).output_template==next_key
    print('PASS original14 families, same/distinct stacks, probability cutoffs, binding, stamina and refusals')


if __name__=='__main__':main()
